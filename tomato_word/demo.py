def demo_books():
    """返回 Book 对象列表。"""
    from .engine import Book

    return [
        Book(book_id=b["book_id"], title=b["title"], author=b["author"], abstract="示例书籍，仅用于界面预览。")
        for b in DEMO_BOOKS
    ]


def demo_chapters(book_id: str):
    from .engine import Chapter

    for b in DEMO_BOOKS:
        if b["book_id"] == book_id:
            return [Chapter(item_id=f"{book_id}-{i}", title=t, volume="") for i, (t, _) in enumerate(b["chapters"])]
    return []


def demo_chapter_text(item_id: str) -> str:
    for b in DEMO_BOOKS:
        for i, (_title, paras) in enumerate(b["chapters"]):
            if item_id == f"{b['book_id']}-{i}":
                return "\n".join(paras)
    return ""
